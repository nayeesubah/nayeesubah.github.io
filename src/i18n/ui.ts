export type UiKey = keyof (typeof ui)[typeof defaultLang];

export function t(locale: string, key: UiKey): string {
  const lang = locale in ui ? (locale as LanguageCode) : defaultLang;
  const dict = ui[lang] as Partial<Record<UiKey, string>>;
  return dict[key] ?? (ui[defaultLang] as Record<UiKey, string>)[key];
}
